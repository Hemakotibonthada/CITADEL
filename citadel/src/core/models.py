@runtime_checkable
class DataFeed(Protocol):
    """Interface for market data feeds."""

    async def connect(self) -> None: ...
    async def disconnect(self) -> None: ...
    async def subscribe(self, symbols: list[str]) -> None: ...
    async def unsubscribe(self, symbols: list[str]) -> None: ...
    async def get_historical_bars(
        self, symbol: str, timeframe: str, start: datetime, end: datetime
    ) -> list[Bar]: ...


@runtime_checkable
class BrokerGateway(Protocol):
    """Interface for broker connections."""

    async def connect(self) -> None: ...
    async def disconnect(self) -> None: ...
    async def submit_order(self, order: Order) -> Order: ...
    async def cancel_order(self, order_id: str) -> bool: ...
    async def get_positions(self) -> list[Position]: ...
    async def get_account_info(self) -> dict[str, Any]: ...
    async def get_order_status(self, order_id: str) -> OrderStatus: ...


@runtime_checkable
class Strategy(Protocol):
    """Interface for trading strategies."""

    @property
    def name(self) -> str: ...

    async def on_bar(self, bar: Bar) -> list[Signal]: ...
    async def on_tick(self, tick: Tick) -> list[Signal]: ...
    def reset(self) -> None: ...


@runtime_checkable
class RiskManager(Protocol):
    """Interface for risk management."""

    def check_order(self, order: Order, portfolio: PortfolioSnapshot) -> tuple[bool, str]: ...
    def check_portfolio(self, portfolio: PortfolioSnapshot) -> list[KillSwitchLevel]: ...
    def get_metrics(self) -> RiskMetrics: ...


@runtime_checkable
class LLMEngine(Protocol):
    """Interface for LLM inference engines."""

    async def generate(self, prompt: str, max_tokens: int = 4096) -> str: ...
    async def generate_stream(self, prompt: str, max_tokens: int = 4096): ...
    def get_device_info(self) -> dict[str, Any]: ...
    async def warmup(self) -> None: ...


@runtime_checkable
class Agent(Protocol):
    """Interface for system agents."""

    @property
    def name(self) -> str: ...

    @property
    def is_alive(self) -> bool: ...

    async def start(self) -> None: ...
    async def stop(self) -> None: ...
    async def heartbeat(self) -> bool: ...


@runtime_checkable
class EventStore(Protocol):
    """Interface for event persistence."""

    async def append(self, event: Event) -> None: ...
    async def get_events(
        self,
        event_type: EventType | None = None,
        start: datetime | None = None,
        end: datetime | None = None,
        limit: int = 1000,
    ) -> list[Event]: ...
    async def replay(self, start: datetime, end: datetime) -> list[Event]: ...


@runtime_checkable
class ReportGenerator(Protocol):
    """Interface for report generation."""

    async def generate_daily_report(self, date: str | None = None) -> str: ...
    async def generate_custom_report(self, sections: list[str]) -> str: ...
    async def email_report(self, report_path: str) -> bool: ...


