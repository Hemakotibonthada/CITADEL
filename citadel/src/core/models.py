class Tick(BaseModel):
    """Single market tick — immutable value object."""
    symbol: str
    timestamp: datetime
    bid: float
    ask: float
    bid_size: float = 0.0
    ask_size: float = 0.0
    last: float = 0.0
    volume: float = 0.0

    @property
    def mid(self) -> float:
        return (self.bid + self.ask) / 2.0

    @property
    def spread(self) -> float:
        return self.ask - self.bid

    model_config = {"frozen": True}


class Bar(BaseModel):
    """OHLCV bar — immutable value object."""
    symbol: str
    timestamp: datetime
    timeframe: str
    open: float
    high: float
    low: float
    close: float
    volume: float
    vwap: float = 0.0
    trades: int = 0

    model_config = {"frozen": True}


class Signal(BaseModel):
    """Trading signal generated by strategy/agent."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
