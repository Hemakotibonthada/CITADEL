def symbol_hash(symbol: str) -> int:
    """FNV-1a 64-bit hash for symbol lookups in shared memory."""
    h = 0xCBF29CE484222325
    for byte in symbol.encode():
        h ^= byte
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h
